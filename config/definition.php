<?php

declare(strict_types=1);

use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition): void {
    $definition->rootNode()
        ->children()
            ->booleanNode('enabled')
                ->defaultTrue()
                ->info('Enable or disable all Twig extensions. Can be overridden per extension.')
            ->end()
            ->scalarNode('prefix')
                ->defaultValue('')
                ->info('Optional prefix before function and filter names. Can be overridden per extension.')
            ->end()
            ->arrayNode('extensions')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('array')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "array" extension configuration.')
                    ->end()
                    ->arrayNode('currency')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "currency" extension configuration.')
                    ->end()
                    ->arrayNode('inline')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->scalarNode('basePath')
                                ->cannotBeEmpty()
                                ->defaultValue('%kernel.project_dir%/templates')
                                ->info(
                                    'Base path to restrict file inlining. ' .
                                    'Also, all calls to the "inline" function will be relative to this path.',
                                )
                            ->end()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "inline" extension configuration.')
                    ->end()
                    ->arrayNode('sort')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "sort" extension configuration.')
                    ->end()
                    ->arrayNode('spaceless')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "spaceless" extension configuration.')
                    ->end()
                    ->arrayNode('time')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('locale')
                                ->defaultNull()
                                ->info('Optional locale for date and time representation.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "time" extension configuration.')
                    ->end()
                    ->arrayNode('type')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->booleanNode('enabled')
                                ->defaultTrue()
                                ->info('Override the root "enabled" setting. Omit to inherit from root.')
                            ->end()
                            ->scalarNode('prefix')
                                ->defaultValue('')
                                ->info('Optional prefix before function and filter names.')
                            ->end()
                        ->end()
                        ->info('Twig "type" extension configuration.')
                    ->end()
                ->end()
            ->end()
        ->end()
    ;
};
